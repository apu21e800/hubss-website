/**
 * lib/image-facts.ts from docs/site-audits/gallery-captions-2026-10-26.csv:
 * the place and the system each gallery photograph can honestly be captioned
 * with (Vern, 26 Oct 2026: "add location and product used to all the
 * images"). The sheet carries, per photo, what the site's own records
 * establish (the map's jobs, the printed Product Portfolio Book's captions,
 * the catalogue assets' manifest, the client's own captions in
 * lib/image-seo.ts, a twin of the photo in a product folder) and two columns
 * for Doug: "Place (Doug)" and "System (Doug)" win over the evidence.
 *
 *   npx tsx scripts/gen-image-facts.ts        # rewrites lib/image-facts.ts
 *
 * A row with no place and no system writes nothing: the photo keeps its
 * folder's line. Nothing here is guessed; a "GPS says near" hint is not a
 * fact until Doug confirms it in his column.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SHEET = path.join(ROOT, "docs/site-audits/gallery-captions-2026-10-26.csv");
const OUT = path.join(ROOT, "lib/image-facts.ts");

function parseCsv(text: string): Record<string, string>[] {
  const rows: string[][] = [];
  let row: string[] = [], cell = "", quoted = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"') { if (text[i + 1] === '"') { cell += '"'; i++; } else quoted = false; }
      else cell += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ",") { row.push(cell); cell = ""; }
    else if (ch === "\n" || ch === "\r") { if (ch === "\r" && text[i + 1] === "\n") i++; row.push(cell); rows.push(row); row = []; cell = ""; }
    else cell += ch;
  }
  if (cell || row.length) { row.push(cell); rows.push(row); }
  const head = rows[0].map((h) => h.replace(/^﻿/, "").trim());
  return rows.slice(1).filter((r) => r.length > 1).map((r) => Object.fromEntries(head.map((h, i) => [h, (r[i] ?? "").trim()])));
}

const rows = parseCsv(readFileSync(SHEET, "utf8"));
const facts: Record<string, { system?: string; place?: string; source: string }> = {};
for (const r of rows) {
  const place = r["Place (Doug)"] || r["place (evidence)"];
  const system = r["System (Doug)"] || r["system (evidence)"];
  if (!place && !system) continue;
  const source = r["Place (Doug)"] || r["System (Doug)"] ? "Doug, from the captions sheet" : (r["source"].split(";")[0] || "the captions sheet").trim();
  facts[r.file] = { ...(system ? { system } : {}), ...(place ? { place } : {}), source };
}
const lines = [
  "/**",
  " * What the site can honestly say under each gallery photograph beyond its",
  " * folder's line: the system, and the place. GENERATED by",
  " * scripts/gen-image-facts.ts from docs/site-audits/gallery-captions-2026-10-26.csv;",
  " * edit the sheet (Doug's two columns win), then run the script. Read by",
  " * lib/image-seo.ts (honestLine). The `source` is the record each fact rests on.",
  " */",
  "export interface ImageFact { system?: string; place?: string; source: string }",
  "",
  "export const IMAGE_FACTS: Record<string, ImageFact> = {",
  ...Object.entries(facts).sort().map(([file, f]) => `  ${JSON.stringify(file)}: ${JSON.stringify(f)},`),
  "};",
  "",
];
writeFileSync(OUT, lines.join("\n"));
console.log(`lib/image-facts.ts: ${Object.keys(facts).length} photographs with a system or a place (${rows.length} in the sheet)`);
