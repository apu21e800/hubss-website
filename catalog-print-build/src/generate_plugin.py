def _generate_qr(dest_path: Path) -> bool:
    """Generate a hubss.com QR code PNG at dest_path. Returns True on success."""
    try:
        import qrcode  # pip install qrcode[pil]
        qr = qrcode.QRCode(
            version=1,
            error_correction=qrcode.constants.ERROR_CORRECT_H,
            box_size=12,
            border=3,
        )
        qr.add_data("https://hubss.com")
        qr.make(fit=True)
        img = qr.make_image(fill_color="black", back_color="white")
        dest_path.parent.mkdir(parents=True, exist_ok=True)
        img.save(dest_path)
        print(f"  QR -> {dest_path.name}")
        return True
    except ImportError:
        print("  QR skipped (pip install qrcode[pil] to enable)")
        return False
    except Exception as e:
        # Don't let QR side-effect kill the main plugin write
        print(f"  QR error (non-fatal): {e}")
        return False


# --- image-URL rewriting: local paths -> hosted (served) URLs the plugin fetches
BOOKLET_MANIFEST = ROOT.parent / "public" / "images" / "catalogue-assets" / "_manifest.json"
_IMG_EXT = (".jpg", ".jpeg", ".png", ".webp")


def _load_booklet_manifest() -> dict:
    if BOOKLET_MANIFEST.exists():
        return json.loads(BOOKLET_MANIFEST.read_text(encoding="utf-8"))
    return {}


def _to_hosted_url(path_str: str, booklet: dict):
    """Map a local image path to a root-relative hosted URL, or None if unmapped."""
    s = path_str.replace("\\", "/")
    low = s.lower()
    if "/public/images/" in low:
        rel = "/images/" + s.split("/public/images/", 1)[1]
        return urllib.parse.quote(rel, safe="/")
    return booklet.get(Path(s).name)  # hosted assets (booklet photos + QR), keyed by basename


def _rewrite_image_urls(node, booklet: dict) -> int:
    """In-place: replace image-path string values with hosted URLs. Returns count."""
    n = 0
    if isinstance(node, dict):
        for k, v in node.items():
            if isinstance(v, str) and v.lower().endswith(_IMG_EXT):
                u = _to_hosted_url(v, booklet)
                if u:
                    node[k] = u
                    n += 1
            elif not isinstance(v, str):
                n += _rewrite_image_urls(v, booklet)
    elif isinstance(node, list):
        for v in node:
            n += _rewrite_image_urls(v, booklet)
    return n


def _load_figma_downscale() -> dict:
    f = ROOT.parent / "public" / "images" / "catalogue-figma" / "_manifest.json"
    if f.exists():
        return json.loads(f.read_text(encoding="utf-8"))
    return {}


def _remap_urls(node, mapping: dict) -> int:
    """In-place: swap any image URL for its downscaled catalogue-figma copy."""
    n = 0
    if isinstance(node, dict):
        for k, v in node.items():
            if isinstance(v, str) and v in mapping:
                node[k] = mapping[v]
                n += 1
            elif not isinstance(v, str):
                n += _remap_urls(v, mapping)
    elif isinstance(node, list):
        for v in node:
            n += _remap_urls(v, mapping)
    return n


