def _generate_qr(dest_path: Path) -> bool:
    """Generate a hubss.com QR code PNG at dest_path. Returns True on success."""
    try:
        import qrcode  # pip install qrcode[pil]
        qr = qrcode.QRCode(
            version=1,
            error_correction=qrcode.constants.ERROR_CORRECT_H,
            box_size=12,
            border=3,
        )
        qr.add_data("https://hubss.com")
        qr.make(fit=True)
        img = qr.make_image(fill_color="black", back_color="white")
        dest_path.parent.mkdir(parents=True, exist_ok=True)
        img.save(dest_path)
        print(f"  QR -> {dest_path.name}")
        return True
    except ImportError:
        print("  QR skipped (pip install qrcode[pil] to enable)")
        return False
    except Exception as e:
        # Don't let QR side-effect kill the main plugin write
        print(f"  QR error (non-fatal): {e}")
        return False


