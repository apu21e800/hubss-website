"""
generate_plugin.py — Write a clean, minimal code.js from catalog_data.json.

The embedded-image version of code.js reaches ~74 MB, which exceeds Figma's
plugin sandbox and prevents loading. This script generates a fresh ~100-200 KB
plugin that builds all 100 Figma frames with:
  - Correct frame names, background colours, navy bands, orange accents
  - All product/project text (name, tagline, body, callout, uses...)
  - Neutral light-grey [PHOTO] placeholder rectangles for every photo slot
  - Correct page order matching the PDF exactly

Usage:
    python -B -m src.export_json          # regenerate catalog_data.json
    python -B -m src.generate_plugin      # write fresh code.js
    python -B -m src.embed_images --lite  # MANDATORY: embed images at
                                          # review quality (~22 MB).
                                          # NEVER ship --print (~67 MB)
                                          # to Vernon — it crashes his
                                          # 30 GB Figma machine.
    Then in Figma: remove plugin, re-import manifest, click Build.
"""
