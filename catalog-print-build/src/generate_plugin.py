  _ensureTextStyle("Body / Small",          "Inter", "Medium",    8, 12,  0.0);
  _ensureTextStyle("Eyebrow / Caps",        "Inter", "Bold",      7, 11,  16.0);
  _ensureTextStyle("TOC / Item",            "Inter", "Bold",     11, 17,  0.0);
  _ensureTextStyle("Page Number",           "Inter", "Medium",    8, 12,  0.0);

